-- Baseline of the schema as ddl-auto=update left it on 2026-09-09.
--
-- Existing databases are baselined at this version (spring.flyway.baseline-version=1) and so never
-- run this file; it exists so a fresh database arrives at the same place. Foreign keys are named
-- here, where Hibernate had generated hashes — validate does not compare constraint names, so the
-- two remain compatible.

CREATE TABLE users (
    id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name                VARCHAR(255),
    email                    VARCHAR(255) NOT NULL UNIQUE,
    password                 VARCHAR(255) NOT NULL,
    role                     VARCHAR(255) NOT NULL CHECK (role IN ('EMPLOYER', 'JOB_SEEKER')),
    phone                    VARCHAR(255),
    bio                      TEXT,
    location                 VARCHAR(255),
    profile_photo_path       VARCHAR(255),
    resume_path              VARCHAR(255),
    experience_years         INTEGER,
    current_job_title        VARCHAR(255),
    linkedin_url             VARCHAR(255),
    github_url               VARCHAR(255),
    portfolio_url            VARCHAR(255),
    is_email_verified        BOOLEAN,
    email_verification_token VARCHAR(255),
    password_reset_token     VARCHAR(255),
    password_reset_expiry    TIMESTAMP(6),
    is_profile_public        BOOLEAN,
    is_banned                BOOLEAN,
    created_at               TIMESTAMP(6),
    updated_at               TIMESTAMP(6)
);

CREATE TABLE user_skills (
    user_id INTEGER NOT NULL REFERENCES users (id),
    skill   VARCHAR(255)
);

CREATE TABLE companies (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    description TEXT,
    website     VARCHAR(255),
    location    VARCHAR(255),
    industry    VARCHAR(255),
    size        VARCHAR(255),
    logo_path   VARCHAR(255),
    owner_id    INTEGER NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP(6)
);

CREATE TABLE job_post (
    post_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_profile   VARCHAR(255),
    post_desc      TEXT,
    req_experience INTEGER,
    posted_by_id   INTEGER REFERENCES users (id),
    company_id     INTEGER REFERENCES companies (id),
    salary_min     NUMERIC(38, 2),
    salary_max     NUMERIC(38, 2),
    location       VARCHAR(255),
    job_type       VARCHAR(255) CHECK (job_type IN
                        ('FULL_TIME', 'PART_TIME', 'CONTRACT', 'INTERNSHIP', 'FREELANCE')),
    is_remote      BOOLEAN,
    is_active      BOOLEAN,
    is_featured    BOOLEAN,
    is_approved    BOOLEAN,
    view_count     INTEGER,
    posted_date    TIMESTAMP(6)
);

CREATE TABLE job_post_post_tech_stack (
    job_post_post_id INTEGER NOT NULL REFERENCES job_post (post_id),
    post_tech_stack  VARCHAR(255)
);

CREATE TABLE job_applications (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_post_id  INTEGER NOT NULL REFERENCES job_post (post_id),
    applicant_id INTEGER NOT NULL REFERENCES users (id),
    cover_letter TEXT,
    status       VARCHAR(255) NOT NULL CHECK (status IN
                     ('PENDING', 'REVIEWED', 'ACCEPTED', 'REJECTED')),
    applied_date TIMESTAMP(6)
);

CREATE TABLE saved_jobs (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES users (id),
    job_post_id INTEGER NOT NULL REFERENCES job_post (post_id),
    saved_at    TIMESTAMP(6),
    UNIQUE (user_id, job_post_id)
);

CREATE TABLE match_scores (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER NOT NULL REFERENCES users (id),
    job_post_id  INTEGER NOT NULL REFERENCES job_post (post_id),
    score        FLOAT(53) NOT NULL,
    generated_at TIMESTAMP(6)
);

CREATE TABLE matched_skills (
    match_score_id INTEGER NOT NULL REFERENCES match_scores (id),
    skill          VARCHAR(255)
);

CREATE TABLE missing_skills (
    match_score_id INTEGER NOT NULL REFERENCES match_scores (id),
    skill          VARCHAR(255)
);

CREATE TABLE notifications (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER NOT NULL REFERENCES users (id),
    title      VARCHAR(255) NOT NULL,
    message    TEXT,
    type       VARCHAR(255) NOT NULL CHECK (type IN
                   ('APPLICATION_RECEIVED', 'APPLICATION_STATUS_CHANGED')),
    action_url VARCHAR(255),
    is_read    BOOLEAN,
    created_at TIMESTAMP(6)
);

CREATE TABLE refresh_tokens (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES users (id),
    token       VARCHAR(255) NOT NULL UNIQUE,
    expiry_date TIMESTAMP(6) NOT NULL,
    revoked     BOOLEAN
);

CREATE INDEX idx_job_post_comparables ON job_post (is_active, location, req_experience);
CREATE INDEX idx_job_post_posted_date ON job_post (posted_date);
