-- The ADMIN role, and the audit trail that makes it safe to hand out.
--
-- No account can self-register as ADMIN: registration rejects any role but the two self-serve ones,
-- and the first admin is promoted at startup from app.admin.email. Admins promote admins after that.

ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check
    CHECK (role IN ('EMPLOYER', 'JOB_SEEKER', 'ADMIN'));

-- One row per admin write. Written in the same transaction as the change it describes, so an
-- action that is not recorded did not happen.
CREATE TABLE admin_actions (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id    INTEGER NOT NULL REFERENCES users (id),
    action      VARCHAR(64) NOT NULL,
    target_type VARCHAR(32) NOT NULL,
    target_id   INTEGER NOT NULL,
    reason      TEXT,
    created_at  TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_admin_actions_target ON admin_actions (target_type, target_id);
CREATE INDEX idx_admin_actions_admin ON admin_actions (admin_id, created_at);
