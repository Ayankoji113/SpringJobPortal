-- Application lifecycle: more stages, a response deadline, and a timeline of every status change.
--
-- An application used to be one of four states with no history and no obligation on the employer
-- to ever answer. respond_by is that obligation; application_events is the history.

ALTER TABLE job_applications DROP CONSTRAINT IF EXISTS job_applications_status_check;
ALTER TABLE job_applications ADD CONSTRAINT job_applications_status_check
    CHECK (status IN ('PENDING', 'REVIEWED', 'INTERVIEW', 'OFFERED', 'ACCEPTED', 'REJECTED',
                      'WITHDRAWN', 'NO_RESPONSE'));

ALTER TABLE job_applications ADD COLUMN respond_by TIMESTAMP(6);
ALTER TABLE job_applications ADD COLUMN responded_at TIMESTAMP(6);
ALTER TABLE job_applications ADD COLUMN reminder_sent_at TIMESTAMP(6);

-- Applications still waiting get a full 14 days from today. Already-decided rows keep a null
-- respond_by: when they were really answered is unknown, so they stay out of the response-rate
-- statistics rather than counting as either a hit or a miss.
UPDATE job_applications
SET respond_by = LOCALTIMESTAMP + INTERVAL '14 days'
WHERE status = 'PENDING';

-- "Already applied" was a read followed by a write with nothing behind it, so two fast clicks could
-- insert twice. Keep the earliest of any such pair, then make the database enforce it.
DELETE FROM job_applications a
    USING job_applications b
WHERE a.job_post_id = b.job_post_id
  AND a.applicant_id = b.applicant_id
  AND a.id > b.id;

CREATE UNIQUE INDEX uq_job_applications_job_applicant
    ON job_applications (job_post_id, applicant_id);

-- The deadline task scans for waiting applications by due date.
CREATE INDEX idx_job_applications_status_respond_by ON job_applications (status, respond_by);

-- One row per status change, written in the same transaction as the change. actor_id is null when
-- the system made the change (a missed deadline, a closed posting).
CREATE TABLE application_events (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id INTEGER NOT NULL REFERENCES job_applications (id) ON DELETE CASCADE,
    from_status    VARCHAR(32),
    to_status      VARCHAR(32) NOT NULL,
    actor_id       INTEGER REFERENCES users (id),
    note           TEXT,
    created_at     TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_application_events_application ON application_events (application_id, created_at);
